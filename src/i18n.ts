// Two languages, one switch in the header. English is the default (judges and partners); Spanish is what
// caregivers and coordinators in Puerto Rico use. Every screen reads its text through useT().

export type Lang = 'en' | 'es'
const KEY = 'vp_lang'

const read = (): Lang => { try { return localStorage.getItem(KEY) === 'es' ? 'es' : 'en' } catch { return 'en' } }
let current: Lang = read()
const listeners = new Set<() => void>()

export const getLang = () => current
export function setLang(next: Lang) {
  current = next
  try { localStorage.setItem(KEY, next) } catch { /* private mode: lasts for this page only */ }
  document.documentElement.lang = next
  listeners.forEach((notify) => notify())
}
export const useLang = () => useSyncExternalStore((notify) => { listeners.add(notify); return () => { listeners.delete(notify) } }, getLang)

