export type TextKey = keyof typeof es
const TEXT: Record<Lang, typeof es> = { es, en }

export function translate(lang: Lang, key: TextKey, values?: Record<string, string | number>) {
  const text = TEXT[lang][key]
  return values ? text.replace(/\{(\w+)\}/g, (whole, name: string) => name in values ? String(values[name]) : whole) : text
}
// const t = useT(); t('some.key'). The component re-renders when the language changes.
export type Translator = (key: TextKey, values?: Record<string, string | number>) => string
// Stable callbacks let ongoing polling and speech handlers use the latest language.
const currentText: Translator = (key, values) => translate(getLang(), key, values)
export function useT() {
  useLang()
  return currentText
}

