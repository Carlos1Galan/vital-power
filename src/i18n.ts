// Translate the select's own empty, loading, and screen-reader messages too.
export function selectText(t: Translator): Pick<SelectProps<{ value: string; label: string }, false>,
  'noOptionsMessage' | 'loadingMessage' | 'screenReaderStatus' | 'ariaLiveMessages'> {
  return {
    noOptionsMessage: () => t('common.noOptions'),
    loadingMessage: () => t('common.loading'),
    screenReaderStatus: ({ count }) => t('common.selectResults', { count }),
    ariaLiveMessages: {
      guidance: ({ context }) => t(context === 'menu' ? 'common.selectMenu' : context === 'value' ? 'common.selectValue' : 'common.selectInput'),
      onChange: ({ action, label, labels, isDisabled }) => {
        if (isDisabled) return t('common.selectDisabled', { label })
        if (action === 'clear') return t('common.selectCleared')
        if (action === 'deselect-option' || action === 'remove-value' || action === 'pop-value') return t('common.selectRemoved', { label })
        return t('common.selectSelected', { label: label || labels.join(', ') })
      },
      onFilter: ({ inputValue, resultsMessage }) => inputValue ? t('common.selectFilter', { results: resultsMessage, input: inputValue }) : resultsMessage,
      onFocus: ({ label, focused, options, selectValue, context, isDisabled }) => {
        if (isDisabled) return t('common.selectDisabled', { label })
        const choices = context === 'value' ? selectValue : options.flatMap((option) => 'options' in option ? option.options : [option])
        return t('common.selectFocused', { label, index: choices.indexOf(focused) + 1, count: choices.length })
      },
    },
  }
}
