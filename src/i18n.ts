export function fromServer(lang: Lang, text: string): string
export function fromServer(lang: Lang, text: string | null | undefined): string | null | undefined
export function fromServer(lang: Lang, text: string | null | undefined) {
  if (!text) return text
  // Errors may already be on screen when the reader changes language.
  for (const key of Object.keys(es) as TextKey[]) {
    if (/error|invalid|voiceNetwork|voicePermission|noMicrophone|noSpeech/i.test(key) && (text === es[key] || text === en[key])) return TEXT[lang][key]
  }
  const sharedErrors: Record<string, [string, string]> = {
    'Body too large': ['Texto demasiado largo', 'This text is too long'],
    'No recorded towns reading with that id': ['No hay una lectura de municipios grabada con ese número', 'No recorded municipality reading has that number'],
    'Organization not found': ['Organización no encontrada', 'Organization not found'],
  }
  if (text in sharedErrors) return sharedErrors[text][lang === 'es' ? 0 : 1]
  if (lang === 'es') return text
  if (text in FIXED_EN) return FIXED_EN[text]
  for (const [pattern, english] of PATTERNS_EN) if (pattern.test(text)) { text = text.replace(pattern, english); break }
  return NAMES_EN.reduce((out, [spanish, english]) => out.split(spanish).join(english), text)
}
